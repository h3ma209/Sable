use std::fs;
use std::path::Path;

fn base64_encode(data: &[u8]) -> String {
    const CHARSET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity((data.len() + 2) / 3 * 4);
    for chunk in data.chunks(3) {
        let b0 = chunk[0];
        let b1 = if chunk.len() > 1 { chunk[1] } else { 0 };
        let b2 = if chunk.len() > 2 { chunk[2] } else { 0 };
        out.push(CHARSET[(b0 >> 2) as usize] as char);
        out.push(CHARSET[(((b0 & 0x03) << 4) | (b1 >> 4)) as usize] as char);
        if chunk.len() > 1 {
            out.push(CHARSET[(((b1 & 0x0f) << 2) | (b2 >> 6)) as usize] as char);
        } else {
            out.push('=');
        }
        if chunk.len() > 2 {
            out.push(CHARSET[(b2 & 0x3f) as usize] as char);
        } else {
            out.push('=');
        }
    }
    out
}

fn svg_data_url(path: &Path) -> String {
    let bytes = fs::read(path).unwrap_or_else(|e| panic!("Failed to read {}: {}", path.display(), e));
    format!("data:image/svg+xml;base64,{}", base64_encode(&bytes))
}

fn png_data_url(path: &Path) -> String {
    let bytes = fs::read(path).unwrap_or_else(|e| panic!("Failed to read {}: {}", path.display(), e));
    format!("data:image/png;base64,{}", base64_encode(&bytes))
}

fn font_data_url(path: &Path) -> String {
    let bytes = fs::read(path).unwrap_or_else(|e| panic!("Failed to read {}: {}", path.display(), e));
    format!("data:font/truetype;base64,{}", base64_encode(&bytes))
}

fn main() {
    println!("cargo:rerun-if-changed=assets");

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let assets_dir = Path::new(&manifest_dir).join("assets");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("embedded_assets.rs");

    let app_icon = png_data_url(&assets_dir.join("app_icon.png"));
    let icon_home = svg_data_url(&assets_dir.join("sidebar/home.svg"));
    let icon_free_up = svg_data_url(&assets_dir.join("sidebar/free-up-space.svg"));
    let icon_apps = svg_data_url(&assets_dir.join("sidebar/apps.svg"));
    let icon_tune_up = svg_data_url(&assets_dir.join("sidebar/tune-up.svg"));
    let icon_file_finder = svg_data_url(&assets_dir.join("sidebar/file-finder.svg"));
    let icon_threat_scan = svg_data_url(&assets_dir.join("sidebar/threat-scan.svg"));
    let icon_big_downloads = svg_data_url(&assets_dir.join("sidebar/big-downloads.svg"));
    let icon_space_lens = svg_data_url(&assets_dir.join("sidebar/space-lens.svg"));
    let icon_cloud_storage = svg_data_url(&assets_dir.join("sidebar/cloud-storage.svg"));
    let icon_now_playing = svg_data_url(&assets_dir.join("sidebar/now-playing.svg"));
    let icon_download = svg_data_url(&assets_dir.join("icons/download.svg"));
    let icon_house = svg_data_url(&assets_dir.join("icons/house.svg"));
    let icon_folder = svg_data_url(&assets_dir.join("icons/folder.svg"));

    let font_regular = font_data_url(&assets_dir.join("Sable-Regular.ttf"));
    let font_semibold = font_data_url(&assets_dir.join("Sable-SemiBold.ttf"));

    let css_raw = fs::read_to_string(assets_dir.join("styles.css"))
        .expect("Failed to read styles.css");
    let css_inlined = css_raw
        .replace("url(\"Sable-Regular.ttf\")", &format!("url(\"{}\")", font_regular))
        .replace("url(\"Sable-SemiBold.ttf\")", &format!("url(\"{}\")", font_semibold));

    let content = format!(
        r#"// Auto-generated by build.rs. Do not edit manually.
pub const APP_ICON: &str = "{app_icon}";
pub const ICON_HOME: &str = "{icon_home}";
pub const ICON_FREE_UP_SPACE: &str = "{icon_free_up}";
pub const ICON_APPS: &str = "{icon_apps}";
pub const ICON_TUNE_UP: &str = "{icon_tune_up}";
pub const ICON_FILE_FINDER: &str = "{icon_file_finder}";
pub const ICON_THREAT_SCAN: &str = "{icon_threat_scan}";
pub const ICON_BIG_DOWNLOADS: &str = "{icon_big_downloads}";
pub const ICON_SPACE_LENS: &str = "{icon_space_lens}";
pub const ICON_CLOUD_STORAGE: &str = "{icon_cloud_storage}";
pub const ICON_NOW_PLAYING: &str = "{icon_now_playing}";
pub const ICON_DOWNLOAD: &str = "{icon_download}";
pub const ICON_HOUSE: &str = "{icon_house}";
pub const ICON_FOLDER: &str = "{icon_folder}";
pub const DEFAULT_APP_ICON: &str = "{icon_apps}";

pub const STYLESHEET: &str = {css_inlined:?};
"#
    );

    fs::write(&dest_path, content).expect("Failed to write embedded_assets.rs");
}
